import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { artifactArchitecture } from './release-contracts.mjs';
const [platform, architecture, artifact, outputDir = '.'] = process.argv.slice(2);
if (!platform || !architecture || !artifact) throw new Error('Usage: node scripts/generate-release-evidence.mjs <platform> <architecture> <artifact> [outputDir]');
if (!['macos', 'windows', 'linux'].includes(platform) || !['arm64', 'x64'].includes(architecture)) throw new Error(`Invalid release target: ${platform}/${architecture}`);
if (artifactArchitecture(platform, basename(artifact)) !== architecture) throw new Error(`Artifact architecture does not match explicit target: ${architecture}`);
const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const pkg = JSON.parse(readFileSync(`${repoRoot}/package.json`, 'utf8'));
const digest = createHash('sha256').update(readFileSync(artifact)).digest('hex');
const artifactName = basename(artifact);
const gitCommit = process.env.GITHUB_SHA || execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' }).trim();
if (!/^[a-f0-9]{40}$/.test(gitCommit)) throw new Error(`Invalid git commit: ${gitCommit}`);
const evidence = { auditVersion: pkg.version, gitCommit, forgeLoopCompatibility: { protocolVersion: 1, schemaProvenanceCommit: '19355e701e191d830c56d64e535835e925843bae' }, platform, architecture, artifact: artifactName, sha256: digest, signing: 'unsigned-preview', workflowRunId: process.env.GITHUB_RUN_ID || 'local' };
writeFileSync(`${outputDir}/RELEASE-EVIDENCE-${artifactName}.json`, `${JSON.stringify(evidence, null, 2)}\n`);
